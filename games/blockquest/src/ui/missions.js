export function evaluateMission(level, config, evidence, warnings = []) {
  const mission = missions[level];
  const configured = warnings.length === 0 && Boolean(mission.matches(config, evidence));
  return { configured, tested: configured && Boolean(mission.tested(evidence)) };
}
